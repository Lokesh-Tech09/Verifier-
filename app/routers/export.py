from __future__ import annotations

import csv
import io
import json
from datetime import datetime, timezone

from fastapi import APIRouter
from fastapi.responses import StreamingResponse
from reportlab.lib import colors
from reportlab.lib.pagesizes import letter
from reportlab.lib.styles import getSampleStyleSheet
from reportlab.lib.units import inch
from reportlab.platypus import (
    Paragraph,
    SimpleDocTemplate,
    Spacer,
    Table,
    TableStyle,
)

from app.core.exceptions import ExportError
from app.models.enums import TallyStatus
from app.models.schemas import ExportRequest

router = APIRouter(prefix="/api", tags=["export"])

_CSV_HEADERS = [
    "Description",
    "Drawing Qty",
    "BOM Qty",
    "Difference",
    "Status",
    "Drawing Unit",
    "BOM Unit",
    "Severity",
    "Action Required",
]


def _export_csv(request: ExportRequest) -> bytes:
    buf = io.StringIO()
    writer = csv.writer(buf, quoting=csv.QUOTE_MINIMAL)
    writer.writerow(_CSV_HEADERS)
    for r in request.results:
        writer.writerow(
            [
                r.description,
                "" if r.drawing_qty is None else r.drawing_qty,
                "" if r.bom_qty is None else r.bom_qty,
                r.difference,
                r.status.value,
                r.draw_unit,
                r.bom_unit,
                r.severity.value,
                r.action_required or "",
            ]
        )
    # UTF-8 with BOM so Excel renders it correctly.
    return ("\ufeff" + buf.getvalue()).encode("utf-8")


def _export_json(request: ExportRequest) -> bytes:
    payload = {
        "job_id": str(request.job_id) if request.job_id else None,
        "generated_at": datetime.now(timezone.utc).isoformat(),
        "results": [r.model_dump(mode="json") for r in request.results],
    }
    return json.dumps(payload, indent=2).encode("utf-8")


def _export_pdf(request: ExportRequest) -> bytes:
    buf = io.BytesIO()
    doc = SimpleDocTemplate(
        buf,
        pagesize=letter,
        topMargin=0.6 * inch,
        bottomMargin=0.6 * inch,
        leftMargin=0.5 * inch,
        rightMargin=0.5 * inch,
    )
    styles = getSampleStyleSheet()
    story = []

    story.append(Paragraph("DrawTally Verification Report", styles["Title"]))
    meta = f"Job: {request.job_id or 'n/a'} &middot; Filename: {request.filename or 'n/a'} &middot; Generated: {datetime.now(timezone.utc).strftime('%Y-%m-%d %H:%M UTC')}"
    story.append(Paragraph(meta, styles["Normal"]))
    story.append(Spacer(1, 0.15 * inch))

    total = len(request.results)
    matched = sum(1 for r in request.results if r.status == TallyStatus.MATCH)
    mismatched = sum(1 for r in request.results if r.status == TallyStatus.MISMATCH)
    missing = total - matched - mismatched
    summary_tbl = Table(
        [["Total Items", "Matched", "Mismatched", "Missing / Extra"], [total, matched, mismatched, missing]],
        colWidths=[1.7 * inch] * 4,
    )
    summary_tbl.setStyle(
        TableStyle(
            [
                ("BACKGROUND", (0, 0), (-1, 0), colors.HexColor("#0c2b4d")),
                ("TEXTCOLOR", (0, 0), (-1, 0), colors.white),
                ("ALIGN", (0, 0), (-1, -1), "CENTER"),
                ("GRID", (0, 0), (-1, -1), 0.5, colors.grey),
                ("FONTSIZE", (0, 0), (-1, -1), 9),
            ]
        )
    )
    story.append(summary_tbl)
    story.append(Spacer(1, 0.25 * inch))

    header = ["Description", "Drawing Qty", "BOM Qty", "Diff", "Status"]
    rows = [header]
    row_styles = []
    for i, r in enumerate(request.results, start=1):
        rows.append(
            [
                r.description,
                "—" if r.drawing_qty is None else f"{r.drawing_qty:g}",
                "—" if r.bom_qty is None else f"{r.bom_qty:g}",
                f"{r.difference:+g}" if r.status != TallyStatus.MATCH else "0",
                r.status.value,
            ]
        )
        if r.status != TallyStatus.MATCH:
            row_styles.append(
                ("BACKGROUND", (0, i), (-1, i), colors.HexColor("#fdeceb"))
            )

    table = Table(rows, colWidths=[2.8 * inch, 1.1 * inch, 1.1 * inch, 0.9 * inch, 1.3 * inch], repeatRows=1)
    table.setStyle(
        TableStyle(
            [
                ("BACKGROUND", (0, 0), (-1, 0), colors.HexColor("#0c2b4d")),
                ("TEXTCOLOR", (0, 0), (-1, 0), colors.white),
                ("FONTSIZE", (0, 0), (-1, -1), 8.5),
                ("GRID", (0, 0), (-1, -1), 0.4, colors.grey),
                ("VALIGN", (0, 0), (-1, -1), "MIDDLE"),
                *row_styles,
            ]
        )
    )
    story.append(table)
    story.append(Spacer(1, 0.3 * inch))
    story.append(Paragraph("Generated by DrawTally", styles["Normal"]))

    doc.build(story)
    return buf.getvalue()


_MEDIA_TYPES = {
    "csv": "text/csv",
    "json": "application/json",
    "pdf": "application/pdf",
}


@router.post("/export")
async def export_report(request: ExportRequest) -> StreamingResponse:
    try:
        if request.format == "csv":
            content = _export_csv(request)
            filename = "drawtally-report.csv"
        elif request.format == "json":
            content = _export_json(request)
            filename = "drawtally-report.json"
        elif request.format == "pdf":
            content = _export_pdf(request)
            filename = "drawtally-report.pdf"
        else:  # pragma: no cover - enum validation prevents this
            raise ExportError(f"Unsupported export format: {request.format}")
    except ExportError:
        raise
    except Exception as exc:
        raise ExportError(f"Failed to generate {request.format} export: {exc}") from exc

    return StreamingResponse(
        io.BytesIO(content),
        media_type=_MEDIA_TYPES[request.format.value if hasattr(request.format, "value") else request.format],
        headers={"Content-Disposition": f'attachment; filename="{filename}"'},
    )
